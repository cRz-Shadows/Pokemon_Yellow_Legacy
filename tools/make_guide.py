#!/usr/bin/env python3
"""Build docs/player_guide.pdf from docs/player_guide.md.

The PDF has the guide's text and screenshots (docs/guide/*.png), plus a table of
the rival's counter for every Pick Starter pick, generated by
tools/rival_counters.py where the guide has the
"<!-- guide: rival counter summary -->" marker.

Only the Markdown the guide uses is supported: # and ## headings, paragraphs,
"-" lists (two levels), numbered lists, tables, images on a line of their own,
**bold**, `code` and [links](...).

Usage: tools/make_guide.py                      build the PDF (needs reportlab)
       tools/make_guide.py --screenshots ROM    recapture docs/guide/*.png by playing
                                                ROM (a prefix: the ROM path without
                                                .gbc) in PyBoy (pip install -r
                                                .github/requirements.txt pillow)
"""

import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
SOURCE = os.path.join(ROOT, 'docs', 'player_guide.md')
OUTPUT = os.path.join(ROOT, 'docs', 'player_guide.pdf')
SHOTS = os.path.join(ROOT, 'docs', 'guide')
SUMMARY_MARKER = '<!-- guide: rival counter summary -->'
# links to repository files point here in the PDF
REPO_URL = 'https://github.com/technicks89/Pokemon_Yellow_Legacy/blob/main/'

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import rival_counters  # noqa: E402


def inline(text):
    """Markdown inline markup to reportlab paragraph markup."""
    text = text.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
    text = re.sub(r'\*\*(.+?)\*\*', r'<b>\1</b>', text)
    text = re.sub(r'(?<![\w*])\*(?!\s)(.+?)\*(?!\w)', r'<i>\1</i>', text)
    text = re.sub(r'`(.+?)`', r'<font face="Courier">\1</font>', text)
    def link(m):
        return f'<link href="{url(m.group(2))}" color="#1a5fb4">{m.group(1)}</link>'
    return re.sub(r'\[(.+?)\]\(([^)]+)\)', link, text)


def url(target):
    """A link target in the guide, as a URL (repository files are on GitHub)."""
    if re.match(r'https?://', target):
        return target
    return REPO_URL + os.path.normpath(os.path.join('docs', target)).replace(os.sep, '/')


def display_name(name):
    """A Pokémon name as the guide writes it: NIDORAN♂ -> Nidoran (M), FARFETCH'D -> Farfetch'd."""
    name = name.replace('♂', ' (M)').replace('♀', ' (F)')
    return re.sub(r"[A-Z][A-Z']*", lambda m: m.group(0).capitalize(), name)


def counter_summary():
    """[(rival's Pokémon, [picks])] in the order of his counter list."""
    _, _, name = rival_counters.species_data()
    _, picks = rival_counters.counter_tables()
    against = {species: [] for species, _, _ in picks}
    for species, counter in rival_counters.all_counters():
        if counter:
            against[counter[0]].append(display_name(name[species]))
    return [(display_name(name[species]), against[species]) for species, _, _ in picks]


def build():
    from reportlab.lib import colors
    from reportlab.lib.enums import TA_CENTER
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import (CondPageBreak, Image, KeepTogether, ListFlowable, ListItem, Paragraph,
                                    SimpleDocTemplate, Spacer, Table, TableStyle)

    styles = getSampleStyleSheet()
    body = ParagraphStyle('body', parent=styles['BodyText'], fontSize=10, leading=13.5, spaceAfter=5)
    cell = ParagraphStyle('cell', parent=body, fontSize=9, leading=11.5, spaceAfter=0)
    title = ParagraphStyle('title', parent=styles['Title'], fontSize=22, spaceAfter=10)
    h2 = ParagraphStyle('h2', parent=styles['Heading2'], fontSize=14, spaceBefore=12, spaceAfter=6,
                        textColor=colors.HexColor('#7a5a00'))
    caption = ParagraphStyle('caption', parent=body, fontSize=8.5, alignment=TA_CENTER,
                             textColor=colors.HexColor('#555555'))
    width = A4[0] - 40 * mm

    def table(rows, col_widths=None):
        data = [[Paragraph(inline(c), cell) for c in row] for row in rows]
        t = Table(data, colWidths=col_widths, repeatRows=1, hAlign='LEFT')
        t.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#f6d743')),
            ('GRID', (0, 0), (-1, -1), 0.4, colors.HexColor('#999999')),
            ('VALIGN', (0, 0), (-1, -1), 'TOP'),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor('#faf6e4')]),
        ]))
        return [t, Spacer(1, 6)]

    def bullets(items):
        flow = []
        for text, sub in items:
            parts = [Paragraph(inline(text), body)]
            if sub:
                parts.append(ListFlowable([ListItem(Paragraph(inline(t), body), leftIndent=12) for t in sub],
                                          bulletType='bullet', start='–', leftIndent=12))
            flow.append(ListItem(parts, leftIndent=12))
        return [ListFlowable(flow, bulletType='bullet', start='•', leftIndent=12)]

    story = []
    with open(SOURCE, encoding='utf-8') as f:
        lines = f.read().splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        if not line.strip():
            i += 1
        elif line.startswith('# '):
            story.append(Paragraph(inline(line[2:]), title))
            i += 1
        elif line.startswith('## '):
            story += [CondPageBreak(30 * mm), Paragraph(inline(line[3:]), h2)]  # no heading at the bottom of a page
            i += 1
        elif line.strip() == SUMMARY_MARKER:
            rows = [["Rival's Pokémon", 'Against your …']]
            rows += [[rival, ', '.join(picks)] for rival, picks in counter_summary()]
            story += table(rows, [32 * mm, width - 32 * mm])
            i += 1
        elif m := re.match(r'!\[(.*)\]\((.+)\)$', line.strip()):
            path = os.path.join(os.path.dirname(SOURCE), m.group(2))
            story.append(KeepTogether([Image(path, width=160 * 1.5, height=144 * 1.5),
                                       Paragraph(inline(m.group(1)), caption)]))
            i += 1
        elif line.startswith('|'):
            rows = []
            while i < len(lines) and lines[i].startswith('|'):
                cells = [c.strip() for c in lines[i].strip().strip('|').split('|')]
                if not all(re.fullmatch(r'-+', c) for c in cells):
                    rows.append(cells)
                i += 1
            story += table(rows)
        elif line.startswith('- '):
            items = []
            while i < len(lines) and (lines[i].startswith('- ') or lines[i].startswith('  - ')):
                if lines[i].startswith('- '):
                    items.append((lines[i][2:], []))
                else:
                    items[-1][1].append(lines[i][4:])
                i += 1
            story += bullets(items)
        elif re.match(r'\d+\. ', line):
            items = []
            while i < len(lines) and re.match(r'\d+\. ', lines[i]):
                items.append(ListItem(Paragraph(inline(lines[i].split('. ', 1)[1]), body), leftIndent=14))
                i += 1
            story.append(ListFlowable(items, bulletType='1', leftIndent=14))
        else:
            text = []
            while i < len(lines) and lines[i].strip() and not re.match(r'(#|\||- |\d+\. |!\[|<!--)', lines[i]):
                text.append(lines[i])
                i += 1
            story.append(Paragraph(inline(' '.join(text)), body))

    def footer(canvas, doc):
        canvas.saveState()
        canvas.setFont('Helvetica', 8)
        canvas.setFillColor(colors.HexColor('#777777'))
        canvas.drawCentredString(A4[0] / 2, 10 * mm, f'Pokémon Yellow Legacy player guide · page {doc.page}')
        canvas.restoreState()

    doc = SimpleDocTemplate(OUTPUT, pagesize=A4, leftMargin=20 * mm, rightMargin=20 * mm, topMargin=18 * mm,
                            bottomMargin=18 * mm, title='Pokémon Yellow Legacy: Player Guide',
                            author='Pokémon Yellow Legacy', invariant=1)
    doc.build(story, onFirstPage=footer, onLaterPages=footer)
    print(f'wrote {os.path.relpath(OUTPUT)}')


def screenshots(prefix):
    """Plays a Pick Starter game (CHARMANDER) and saves the guide's screenshots."""
    sys.path.insert(0, os.path.join(ROOT, '.github', 'scripts'))
    import smoke_test as st

    def save(g, name):
        g.pb.tick(3, True)  # render a few frames: run() skips rendering
        image = g.pb.screen.image.convert('RGB')
        image.resize((image.width * 3, image.height * 3), resample=0).save(os.path.join(SHOTS, name))  # nearest
        print(f'saved docs/guide/{name}')

    os.makedirs(SHOTS, exist_ok=True)
    g = st.Game(prefix, 'guide screenshots')
    try:
        st.choose_mode(g, 2)
        st.open_intro_picker(g)
        g.run(60)
        for _ in range(3):
            g.press('down', 16, hold=8)
        g.run(120)
        save(g, 'picker.png')
        st.pick(g, [])
        st.finish_intro(g)
        st.walk_to_oaks_lab(g)
        st.check_ball(g)
        for _ in range(400):
            if 'just for you' in ' '.join(g.text().split()):
                save(g, 'oak.png')
                break
            g.press('a', 25)
        else:
            g.fail("Oak's text never appeared")
        for _ in range(400):
            if g.mem('wPartyCount'):
                break
            g.press('b' if 'nickname' in g.text() else 'a', 25)
        for _ in range(60):
            t = g.text()
            if 'want a' in t and 'SQUIRTLE' in t[t.find('want a'):]:  # his counter to CHARMANDER
                save(g, 'rival.png')
                return
            g.press('down', 10, hold=12)
            g.press('a', 25)
        g.fail('the rival never asked for his counter')
    finally:
        g.stop()


def main():
    if len(sys.argv) == 3 and sys.argv[1] == '--screenshots':
        screenshots(sys.argv[2])
    elif len(sys.argv) == 1:
        build()
    else:
        print(__doc__)
        return 2
    return 0


if __name__ == '__main__':
    sys.exit(main())
