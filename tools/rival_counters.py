#!/usr/bin/env python3
"""The rival's counter to every Pick Starter pick, computed the way the game does.

A model of PickStarterSetRivalStarter (engine/menus/pick_starter.asm), read straight
from the assembly: the type chart, each species' types, the starter-line counters
(PickStarterRivalCounters) and the candidates (PickStarterRivalCounterPicks). The
docs table in docs/pick_starter_mode.md is generated from it, and the unit and
scenario tests use it for their expected values.

Usage: tools/rival_counters.py           print the docs table (Markdown)
       tools/rival_counters.py --check   fail if the docs table is out of date
"""

import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
DOCS = 'docs/pick_starter_mode.md'
TABLE_START = '<!-- rival counters: generated by tools/rival_counters.py -->'
TABLE_END = '<!-- end of rival counters -->'

NEUTRAL = 4  # NEUTRAL_TYPE_SCORE
LOG = {'SUPER_EFFECTIVE': 1, 'NOT_VERY_EFFECTIVE': -1}


def read(path):
    with open(os.path.join(ROOT, path), encoding='utf-8') as f:
        return f.read()


def asm_block(path, label):
    """The lines of label's block, up to the next blank line."""
    return read(path).split(label + ':')[1].split('\n\n')[0]


def type_chart():
    return {(a, d): e for a, d, e in re.findall(
        r'^\s*db\s+(\w+),\s*(\w+),\s*(\w+)', read('data/types/type_matchups.asm'), re.MULTILINE)}


def species_data():
    """({species: (type1, type2)}, [species in Pokédex order], {species: name})."""
    types, dex = {}, []
    for path in re.findall(r'INCLUDE "(data/pokemon/base_stats/\w+\.asm)"', read('data/pokemon/base_stats.asm')):
        text = read(path)
        species = re.search(r'db DEX_(\w+)', text).group(1)
        types[species] = tuple(re.search(r'db (\w+), (\w+) ; type', text).groups())
        dex.append(species)
    ids = re.findall(r'^\tconst (\w+)', read('constants/pokemon_constants.asm').split('const_def')[1],
                     re.MULTILINE)
    names = re.findall(r'db "([^"]+)"', read('data/pokemon/names.asm'))
    name = {s: names[i - 1].rstrip('@') for i, s in enumerate(ids) if i and i <= len(names)}
    return types, dex, name


def counter_tables():
    """(starter-line counters {pick: rival starter}, candidates [(species, team, line)])."""
    src = 'engine/menus/pick_starter.asm'
    starter_lines = dict(re.findall(r'db (\w+),\s*RIVAL_STARTER_(\w+)', asm_block(src, 'PickStarterRivalCounters')))
    picks, line = [], 0
    for kind, species, team in re.findall(r'^\s*(db|rival_counter_line) (\w+),\s*RIVAL_STARTER_(\w+)',
                                          asm_block(src, 'PickStarterRivalCounterPicks'), re.MULTILINE):
        if kind == 'rival_counter_line':
            line += 1
            picks.append((species, team, line))
        else:
            picks.append((species, team, 0))
    return starter_lines, picks


def score(chart, attacker, defenders):
    """PickStarter_TypeScore."""
    total = NEUTRAL
    for d in dict.fromkeys(defenders):  # a single type counts once
        e = chart.get((attacker, d), 'EFFECTIVE')
        if e == 'NO_EFFECT':
            return 0
        total += LOG.get(e, 0)
    return total


def best_score(chart, attackers, defenders):
    """PickStarter_BestTypeScore."""
    return max(score(chart, a, defenders) for a in dict.fromkeys(attackers))


def rival_counter(pick, chart, types, starter_lines, picks):
    """The rival's Pokémon against pick: (species, team) or None if he keeps his EEVEE."""
    if pick in starter_lines:
        return starter_lines[pick], starter_lines[pick]
    if pick == 'PIKACHU':
        return None
    best, best_attack, best_defense = None, NEUTRAL, 0
    for species, team, _ in picks:
        attack = best_score(chart, types[species], types[pick])
        if attack < best_attack:
            continue
        defense = best_score(chart, types[pick], types[species])
        if attack == best_attack and defense >= best_defense:
            continue
        best, best_attack, best_defense = (species, team), attack, defense
    return best


def all_counters():
    """[(species, rival's Pokémon or None)] in Pokédex order."""
    chart = type_chart()
    types, dex, _ = species_data()
    starter_lines, picks = counter_tables()
    return [(s, rival_counter(s, chart, types, starter_lines, picks)) for s in dex]


def markdown():
    types, _, name = species_data()

    def show(t):
        return '/'.join(dict.fromkeys(x.replace('_TYPE', '') for x in t))

    rows = ['| Your Pokémon | Types | Rival\'s Pokémon |', '|---|---|---|']
    for species, counter in all_counters():
        rival = name[counter[0]] if counter else 'EEVEE, as in Normal mode' if species == 'PIKACHU' else 'EEVEE'
        rows.append(f'| {name[species]} | {show(types[species])} | {rival} |')
    return '\n'.join([TABLE_START, ''] + rows + ['', TABLE_END])


def docs_table():
    text = read(DOCS)
    start, end = text.find(TABLE_START), text.find(TABLE_END)
    return text[start:end + len(TABLE_END)] if start >= 0 and end > start else None


def main():
    if sys.argv[1:] == ['--check']:
        if docs_table() != markdown():
            print(f'{DOCS}: the rival counter table is out of date; run tools/rival_counters.py and paste it in')
            return 1
        return 0
    print(markdown())
    return 0


if __name__ == '__main__':
    sys.exit(main())
